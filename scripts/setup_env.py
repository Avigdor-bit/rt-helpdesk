#!/usr/bin/env python3
"""Generate a local .env with random passwords (per docs/CONTAINER_PACKAGING.md).

Creates/overwrites .env in the repository root with fresh secrets.
The init script postgres/init/01-app-role.sh uses APP_DB_PASSWORD to set the
helpdesk_app role password; the Flask app authenticates with DB_PASSWORD.
Both MUST hold the same value.

Never commit .env (it is in .gitignore).
"""
import secrets
import string
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV = ROOT / ".env"

def rand(n: int = 24) -> str:
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(n))

app_password = rand()
content = f"""# Generated by scripts/setup_env.py — DO NOT COMMIT
POSTGRES_PASSWORD={rand()}
APP_DB_PASSWORD={app_password}
DB_PASSWORD={app_password}
GRAFANA_ADMIN_PASSWORD={rand()}
DB_ADMIN_USER=helpdesk_admin
DB_USER=helpdesk_app
DB_NAME=helpdesk
APP_VERSION=local
APP_ENV=development
"""
ENV.write_text(content)
ENV.chmod(0o600)
print(f"wrote {ENV}")
